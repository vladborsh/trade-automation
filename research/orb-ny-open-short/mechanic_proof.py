#!/usr/bin/env python3
"""DESIGN.md §10 step 3 — `MECHANIC-PROOF.md`.

**Ten fit-period trades per OR width** (30 trades), shown minute by minute: the
opening range, the bars that did NOT trigger and why, the trigger bar, the
stop, the exit minute and the feature vector. A reader who disagrees with the
mechanic can disagree with a specific number here.

The point this file has to make for THIS family: the first candidate bar of
every trade is the 5m bar opening at the arm's own range end — 09:35 / 09:40 /
09:45 NY — and not 10:00. The candidate-bar table below starts there, so the
bug the closed pass had is visible or absent on the page.

    python mechanic_proof.py
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C  # noqa: E402
import engine as E  # noqa: E402
import features as F  # noqa: E402

N_PER_WIDTH = 10


def ny(t) -> str:
    return pd.Timestamp(int(t), unit="ms", tz="UTC").tz_convert(C.SESSION_TZ) \
        .strftime("%H:%M")


def main() -> None:
    q = pd.read_parquet(os.path.join(C.RESULTS, "trades_all.parquet"))
    q = q[q.period == "fit"]
    rng = np.random.default_rng(C.SEED)
    out = ["# MECHANIC-PROOF — ten fit-period trades per opening-range width, in full",
           "",
           "Generated by `mechanic_proof.py`. Every number below is read off the "
           "tape by the same code that produces `results/trades_all.parquet`; "
           "nothing is retyped by hand. The point is that the mechanic of "
           "`DESIGN.md` §3 can be audited on a specific day rather than trusted.",
           "",
           "Conventions recalled: the opening range is the 1-minute high/low "
           "over [09:30, 09:30 + width) NY; the first eligible trigger bar is "
           "the **5-minute bar opening at the range\'s end** (09:35 / 09:40 / "
           "09:45 NY); a bar triggers on its **close** strictly beyond the "
           "range, never on a touch; entry is that bar\'s close; the stop is "
           "the opposite side of the range; template 1 targets +1R and is "
           "forced flat at 16:00 NY; the exit path is walked on **1-minute** "
           "bars with the stop checked first.", ""]
    for orm in C.OR_WIDTHS:
        g = q[q.or_min == orm]
        pick = rng.choice(g.index.values, size=N_PER_WIDTH, replace=False)
        ts = C.trig_start(orm)
        out += ["---", "",
                f"## {orm}-minute opening range — {N_PER_WIDTH} trades "
                f"(trigger window opens {ts[0]:02d}:{ts[1]:02d} NY)", ""]
        for i in pick:
            out += trade_block(q.loc[i], C.TF)
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "MECHANIC-PROOF.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote MECHANIC-PROOF.md")


def trade_block(r, tf) -> list[str]:
    tp = E.Tape.get(r.symbol)
    B = tp.bars[tf]
    side = "LONG" if r.side > 0 else "SHORT"
    L = [f"### {r['arm']} · {r['date']} · **{side}**", ""]
    t_start = C.trig_start(int(r.or_min))
    L += [f"- **Opening range** 09:30–{C.trig_start(int(r.or_min))[0]:02d}:"
          f"{C.trig_start(int(r.or_min))[1]:02d} NY ({int(r.or_min)} min), "
          f"from the 1m tape: "
          f"`OR_high = {r.or_high:g}`, `OR_low = {r.or_low:g}`, width "
          f"`{r.or_high - r.or_low:g}` "
          f"({int(r.i_or1 - r.i_or0) + 1} 1-minute bars).",
          f"- **Forced flat** at the {ny(tp.t[int(r.i_flat)])} NY minute "
          f"(the last bar ending ≤ 16:00 NY)."]
    # the candidate bars, in order, up to and including the trigger
    a = np.searchsorted(B["t"], C.ny_ms(r["date"], *t_start), "left")
    L += ["", f"The candidate {tf}m bars, from the range\'s end "
          f"({t_start[0]:02d}:{t_start[1]:02d} NY) to the trigger:", "",
          f"| {tf}m bar (NY open) | close | vs range | triggers? |",
          "|---|---|---|---|"]
    for j in range(a, int(r.j) + 1):
        cl = B["c"][j]
        if cl > r.or_high:
            vs, t_ = f"**{cl - r.or_high:+g} above OR_high**", "**YES → long**"
        elif cl < r.or_low:
            vs, t_ = f"**{cl - r.or_low:+g} below OR_low**", "**YES → short**"
        else:
            vs, t_ = "inside the range", "no"
        L.append(f"| {ny(B['t'][j])} | {cl:g} | {vs} | {t_} |")
    tgt = r.entry + r.side * r.stop_dist
    L += ["", f"- **Entry** = the trigger bar's close = `{r.entry:g}` "
          f"(the {ny(tp.t[int(r.i_entry_min)])} NY 1-minute bar's close).",
          f"- **Stop** = the opposite side of the range = `{r.stop:g}`; "
          f"`stop_dist = 1R = {r.stop_dist:g}`.",
          f"- **Target (template 1)** = `{tgt:g}` (+1R).",
          f"- **Exit, template 1:** {ny(tp.t[int(r.i_exit_1)])} NY at "
          f"`{r.exit_px_1:g}` — *{r.exit_1}* → gross `{r.grossR_1:+.4f}R`, cost "
          f"`{r.cost_R_1:.4f}R`, **net `{r.netR_1:+.4f}R`**.",
          f"- **Exit, template 2 (pure ORB, no target):** "
          f"{ny(tp.t[int(r.i_exit_2)])} NY at `{r.exit_px_2:g}` — *{r.exit_2}* → "
          f"net `{r.netR_2:+.4f}R`.", ""]
    # the minutes around the template-1 exit
    x = int(r.i_exit_1)
    lo = max(int(r.i_entry_min) + 1, x - 3)
    L += ["The 1-minute path at the exit (stop checked first; a minute that "
          "opens through the stop fills at its open):", "",
          "| NY minute | open | high | low | close |", "|---|---|---|---|---|"]
    for z in range(lo, min(x + 2, tp.n)):
        mark = " ←" if z == x else ""
        L.append(f"| {ny(tp.t[z])}{mark} | {tp.o[z]:g} | {tp.h[z]:g} | "
                 f"{tp.l[z]:g} | {tp.c[z]:g} |")
    L += ["", "The feature vector at the entry bar\'s close (descriptive — "
          "**no model is trained on these and no flag is reported**, note §5.5):", "",
          "| feature | value | feature | value |", "|---|---|---|---|"]
    half = (len(F.FEATURES) + 1) // 2
    for k in range(half):
        a1 = F.FEATURES[k]
        row = f"| `{a1}` | {_v(r[a1])} |"
        if k + half < len(F.FEATURES):
            a2 = F.FEATURES[k + half]
            row += f" `{a2}` | {_v(r[a2])} |"
        else:
            row += " | |"
        L.append(row)
    L.append("")
    return L


def _v(x):
    return "—" if pd.isna(x) else f"{x:.4f}"


if __name__ == "__main__":
    main()
