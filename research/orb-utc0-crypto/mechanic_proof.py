#!/usr/bin/env python3
"""DESIGN.md §10 step 4 — `MECHANIC-PROOF.md`.

Ten fit-period trades **per arm**, shown minute by minute: the opening range,
the bars that did NOT trigger and why, the trigger bar, the stop, and the exit
minute. A reader who disagrees with the mechanic can disagree with a specific
number here. No feature vector — this package has none (§4.10 of the note).

    python mechanic_proof.py
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C  # noqa: E402
import engine as E  # noqa: E402

N_PER_ARM = 10
TF = C.TFS[0]


def u(t) -> str:
    return pd.Timestamp(int(t), unit="ms", tz="UTC").strftime("%H:%M")


def main() -> None:
    q = pd.read_parquet(os.path.join(C.RESULTS, "trades_all.parquet"))
    q = q[q.period == "fit"]
    rng = np.random.default_rng(C.SEED)
    out = ["# MECHANIC-PROOF — ten fit-period trades per arm, shown in full",
           "",
           "Generated by `mechanic_proof.py`. Every number below is read off the "
           "tape by the same code that produces `results/trades_all.parquet`; "
           "nothing is retyped by hand. The point is that the mechanic of "
           "`DESIGN.md` §3 can be audited on a specific day rather than trusted.",
           "",
           "Conventions recalled: the opening range is the **00:00–00:30 UTC** "
           "1-minute high/low; a 5-minute bar triggers on its **close** strictly "
           "beyond it, never on a touch; the trigger window is **[00:30, 02:30) "
           "UTC**; entry is the trigger bar's close; the stop is the opposite "
           "side of the range; template 1 targets +1R and is forced flat at "
           "**07:55 UTC** (five minutes before the 08:00 UTC funding "
           "settlement); the exit path is walked on **1-minute** bars with the "
           "stop checked first. Every day of the week is eligible — the sample "
           "below deliberately contains weekend days.", ""]
    for sym in C.INSTRUMENTS:
        g = q[q.symbol == sym]
        # take five weekday and five weekend trades, so the proof covers the
        # days the §8.1 falsification control turns on
        wk = g[~g.weekend]
        we = g[g.weekend]
        pick = list(rng.choice(wk.index.values, size=min(5, len(wk)), replace=False)) \
            + list(rng.choice(we.index.values, size=min(5, len(we)), replace=False))
        out += ["---", "", f"## {sym}-{TF}m — {len(pick)} trades "
                           f"({min(5, len(wk))} weekday, {min(5, len(we))} weekend)", ""]
        for i in pick:
            out += trade_block(q.loc[i])
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "MECHANIC-PROOF.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote MECHANIC-PROOF.md")


def trade_block(r) -> list[str]:
    tp = E.Tape.get(r.symbol)
    B = tp.bars[TF]
    side = "LONG" if r.side > 0 else "SHORT"
    dow = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"][int(r.dow)]
    L = [f"### {r['arm']} · {r['date']} ({dow}"
         + (", **weekend**" if r.weekend else "") + f") · **{side}**", ""]
    L += [f"- **Opening range** 00:00–00:30 UTC, from the 1m tape: "
          f"`OR_high = {r.or_high:g}`, `OR_low = {r.or_low:g}`, width "
          f"`{r.or_high - r.or_low:g}` "
          f"({int(r.i_or1 - r.i_or0) + 1} 1-minute bars).",
          f"- **Forced flat** at the {u(tp.t[int(r.i_flat)])} UTC minute "
          f"(the last bar ending ≤ 07:55 UTC)."]
    t0, _ = E.trig_bounds(r["date"])
    a = np.searchsorted(B["t"], t0, "left")
    L += ["", f"| 5m bar (UTC open) | close | vs range | triggers? |",
          "|---|---|---|---|"]
    for j in range(a, int(r.j) + 1):
        cl = B["c"][j]
        if cl > r.or_high:
            vs, t_ = f"**{cl - r.or_high:+g} above OR_high**", "**YES → long**"
        elif cl < r.or_low:
            vs, t_ = f"**{cl - r.or_low:+g} below OR_low**", "**YES → short**"
        else:
            vs, t_ = "inside the range", "no"
        L.append(f"| {u(B['t'][j])} | {cl:g} | {vs} | {t_} |")
    tgt = r.entry + r.side * r.stop_dist
    L += ["", f"- **Entry** = the trigger bar's close = `{r.entry:g}` "
          f"(the {u(tp.t[int(r.i_entry_min)])} UTC 1-minute bar's close).",
          f"- **Stop** = the opposite side of the range = `{r.stop:g}`; "
          f"`stop_dist = 1R = {r.stop_dist:g}`.",
          f"- **Target (template 1)** = `{tgt:g}` (+1R).",
          f"- **Exit, template 1:** {u(tp.t[int(r.i_exit_1)])} UTC at "
          f"`{r.exit_px_1:g}` — *{r.exit_1}* → gross `{r.grossR_1:+.4f}R`, cost "
          f"`{r.cost_R_1:.4f}R`, **net `{r.netR_1:+.4f}R`**.",
          f"- **Exit, template 2 (pure ORB, no target):** "
          f"{u(tp.t[int(r.i_exit_2)])} UTC at `{r.exit_px_2:g}` — *{r.exit_2}* → "
          f"net `{r.netR_2:+.4f}R`.", ""]
    x = int(r.i_exit_1)
    lo = max(int(r.i_entry_min) + 1, x - 3)
    L += ["The 1-minute path at the exit (stop checked first; a minute that "
          "opens through the stop fills at its open):", "",
          "| UTC minute | open | high | low | close |", "|---|---|---|---|---|"]
    for z in range(lo, min(x + 2, tp.n)):
        mark = " ←" if z == x else ""
        L.append(f"| {u(tp.t[z])}{mark} | {tp.o[z]:g} | {tp.h[z]:g} | "
                 f"{tp.l[z]:g} | {tp.c[z]:g} |")
    L.append("")
    return L


if __name__ == "__main__":
    main()
