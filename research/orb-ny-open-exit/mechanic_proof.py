#!/usr/bin/env python3
"""DESIGN.md §10 step 3 — `MECHANIC-PROOF.md`.

**Ten fit-period trades per exit construction** (30 trades), shown minute by
minute: the opening range, the candidate bars that did NOT trigger and why,
the trigger bar, the stop and where it came from, the exit minute, and the
feature vector. A reader who disagrees with the mechanic can disagree with a
specific number here.

The two points this file has to make for THIS family:

  * for **E1**, the **ratchet path minute by minute** — `best` and `stop`
    after every live minute, until the exit — so that the rule "minute k is
    tested against the stop as of the end of minute k-1, and only then may
    minute k move it" is visible on the page rather than trusted;
  * for **E2**, the **dATR14 value, the session-day bar it was read off, that
    bar's 16:00 NY close, and the resulting stop** — so that the stop is
    visibly knowable before the trade day opens.

    python mechanic_proof.py
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C  # noqa: E402
import engine as E  # noqa: E402
import features as F  # noqa: E402

N_PER_CONSTRUCTION = 10
MAX_RATCHET_ROWS = 60


def ny(t) -> str:
    return pd.Timestamp(int(t), unit="ms", tz="UTC").tz_convert(C.SESSION_TZ) \
        .strftime("%H:%M")


def main() -> None:
    q = pd.read_parquet(os.path.join(C.RESULTS, "trades_all.parquet"))
    q = q[q.period == "fit"]
    rng = np.random.default_rng(C.SEED)
    out = ["# MECHANIC-PROOF — ten fit-period trades per exit construction, in full",
           "",
           "Generated by `mechanic_proof.py`. Every number below is read off the "
           "tape by the same code that produces `results/trades_all.parquet`; "
           "nothing is retyped by hand. The point is that the mechanic of "
           "`DESIGN.md` §3 can be audited on a specific day rather than trusted.",
           "",
           "Conventions recalled: the opening range is the 1-minute high/low "
           "over [09:30, 09:35) NY; the first eligible trigger bar is the "
           "**5-minute bar opening at the range's end, 09:35 NY**; a bar "
           "triggers on its **close** strictly beyond the range, never on a "
           "touch; entry is that bar's close; one trade per day, no re-entry; "
           "**no arm in this family has a target**; every arm is forced flat "
           "at the 16:00 NY minute's close; the exit path is walked on "
           "**1-minute** bars with the stop checked first, and a minute that "
           "opens through the stop fills at that minute's open.",
           "",
           "The three constructions:", ""]
    for k in C.CONSTRUCTIONS:
        out.append(f"- **{k}** — {C.CONSTRUCTION_DESC[k]}.")
    out.append("")
    for k in C.CONSTRUCTIONS:
        g = q[q.construction == k]
        pick = rng.choice(g.index.values, size=N_PER_CONSTRUCTION, replace=False)
        out += ["---", "",
                f"## {k} — {C.CONSTRUCTION_DESC[k]} — {N_PER_CONSTRUCTION} trades", ""]
        for i in pick:
            out += trade_block(q.loc[i], C.TF)
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "MECHANIC-PROOF.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote MECHANIC-PROOF.md")


def trade_block(r, tf) -> list[str]:
    tp = E.Tape.get(r.symbol)
    B = tp.bars[tf]
    side = "LONG" if r.side > 0 else "SHORT"
    k = r.construction
    L = [f"### {r['arm']} · {r['date']} · **{side}**", ""]
    t_start = C.TRIG_START
    L += [f"- **Opening range** 09:30–{t_start[0]:02d}:{t_start[1]:02d} NY "
          f"({int(r.or_min)} min), from the 1m tape: "
          f"`OR_high = {r.or_high:g}`, `OR_low = {r.or_low:g}`, width "
          f"`{r.or_high - r.or_low:g}` "
          f"({int(r.i_or1 - r.i_or0) + 1} 1-minute bars).",
          f"- **Forced flat** at the {ny(tp.t[int(r.i_flat)])} NY minute "
          f"(the last bar ending ≤ 16:00 NY)."]
    a = np.searchsorted(B["t"], C.ny_ms(r["date"], *t_start), "left")
    L += ["", f"The candidate {tf}m bars, from the range's end "
          f"({t_start[0]:02d}:{t_start[1]:02d} NY) to the trigger:", "",
          f"| {tf}m bar (NY open) | close | vs range | triggers? |",
          "|---|---|---|---|"]
    for j in range(a, int(r.j) + 1):
        cl = B["c"][j]
        if cl > r.or_high:
            vs, t_ = f"**{cl - r.or_high:+g} above OR_high**", "**YES → long**"
        elif cl < r.or_low:
            vs, t_ = f"**{cl - r.or_low:+g} below OR_low**", "**YES → short**"
        else:
            vs, t_ = "inside the range", "no"
        L.append(f"| {ny(B['t'][j])} | {cl:g} | {vs} | {t_} |")
    L += ["", f"- **Entry** = the trigger bar's close = `{r.entry:g}` "
          f"(the {ny(tp.t[int(r.i_entry_min)])} NY 1-minute bar's close)."]

    # ---- the stop, and where it came from -------------------------------
    if k == "E2":
        D = F.DayBars.get(r.symbol)
        i = int(np.searchsorted(D.df.date.values, r["date"], "left")) - 1
        bar = D.df.iloc[i]
        L += [f"- **Stop (E2)** = `entry {'−' if r.side > 0 else '+'} "
              f"{C.DATR_FRAC:g} × dATR14` = `{r.stop:g}`; "
              f"`stop_dist = 1R = {r.stop_dist:g}`. The stop is **not** clipped "
              f"to the range in either direction.",
              f"- **dATR14 = `{r.datr14:g}`**, read off the session-day bar "
              f"labelled **{bar.date}** — the bar spanning "
              f"[16:00 NY of the previous calendar day, 16:00 NY of {bar.date}), "
              f"whose OHLC is "
              f"`{bar.open:g} / {bar.high:g} / {bar.low:g} / {bar['close']:g}` "
              f"and whose close is the **16:00 NY close of the PRIOR trading "
              f"day**. Wilder ATR(14) over those bars as of that close. Nothing "
              f"from {r['date']} enters it — `checks.py datr` recomputes it from "
              f"a tape truncated at 09:30 NY of the trade day and requires an "
              f"exact match.",
              f"- For scale: the opening range is `{r.or_high - r.or_low:g}` "
              f"= `{(r.or_high - r.or_low) / r.datr14:.3f} dATR14`, and this "
              f"stop is `{C.DATR_FRAC:g} dATR14`, i.e. "
              f"`{r.stop_dist / (r.or_high - r.or_low):.2f}×` the range width."]
    else:
        L += [f"- **Stop ({k})** = the opposite side of the range = "
              f"`{r.stop:g}`; `stop_dist = 1R = {r.stop_dist:g}`."]
    L += [f"- **Target:** none. `+∞` (long) / `−∞` (short) — no arm in this "
          f"family has a target.",
          f"- **Exit:** {ny(tp.t[int(r.i_exit)])} NY at `{r.exit_px:g}` — "
          f"*{r['exit']}* → gross `{r.grossR:+.4f}R`, cost `{r.cost_R:.4f}R`, "
          f"**net `{r.netR:+.4f}R`**.",
          f"- MFE over the same horizon `{r.mfe_R:+.3f}R`, so the **harvest "
          f"ratio** is `{r.harvest:+.3f}`.", ""]

    # ---- E1: the ratchet path, minute by minute -------------------------
    if k == "E1":
        L += _ratchet_path(tp, r)
    # ---- the minutes around the exit ------------------------------------
    x = int(r.i_exit)
    lo = max(int(r.i_entry_min) + 1, x - 3)
    L += ["The 1-minute path at the exit (stop checked first; a minute that "
          "opens through the stop fills at its open):", "",
          "| NY minute | open | high | low | close |", "|---|---|---|---|---|"]
    for z in range(lo, min(x + 2, tp.n)):
        mark = " ←" if z == x else ""
        L.append(f"| {ny(tp.t[z])}{mark} | {tp.o[z]:g} | {tp.h[z]:g} | "
                 f"{tp.l[z]:g} | {tp.c[z]:g} |")
    L += ["", "The feature vector at the entry bar's close (descriptive — "
          "**no model is trained on these and no flag is reported**; there is "
          "no Study B in this family):", "",
          "| feature | value | feature | value |", "|---|---|---|---|"]
    half = (len(F.FEATURES) + 1) // 2
    for kk in range(half):
        a1 = F.FEATURES[kk]
        row = f"| `{a1}` | {_v(r[a1])} |"
        if kk + half < len(F.FEATURES):
            a2 = F.FEATURES[kk + half]
            row += f" `{a2}` | {_v(r[a2])} |"
        else:
            row += " | |"
        L.append(row)
    L.append("")
    return L


def _ratchet_path(tp, r) -> list[str]:
    """The E1 ratchet, replayed minute by minute with the pure-Python
    reference's own rule order, so the page shows exactly what the walker did:
    each row is minute k, the stop it was TESTED against (as of the end of
    minute k-1), and the `best` / `stop` it left behind for minute k+1."""
    b0, b1 = int(r.i_entry_min) + 1, int(r.i_flat)
    R = float(r.stop_dist)
    d = C.TRAIL_R * R
    best, stop = float(r.entry), float(r.stop)
    L = [f"**The 1R ratchet, minute by minute.** Trail distance = `1R = {R:g}` "
         f"by construction — there is no free parameter. `stop_0 = {stop:g}`. "
         f"Minute k is tested against the stop **as of the end of minute k−1**; "
         f"only then may minute k move it, for minute k+1 onward. The stop only "
         f"ever tightens, so the first live minute is tested against `stop_0` "
         f"and E1 can never exit earlier or worse than E0 on the same minute.",
         "",
         "| NY minute | high | low | tested against stop | hit? | best after | "
         "stop after | moved? |", "|---|---|---|---|---|---|---|---|"]
    n = 0
    for k in range(b0, b1 + 1):
        tested = stop
        if r.side > 0:
            hit = tp.l[k] <= stop
            gap = tp.o[k] <= stop
        else:
            hit = tp.h[k] >= stop
            gap = tp.o[k] >= stop
        if hit:
            px = tp.o[k] if gap else stop
            cause = "stop (ratchet never moved)" if stop == float(r.stop) else "trail-stop"
            L.append(f"| **{ny(tp.t[k])}** | {tp.h[k]:g} | {tp.l[k]:g} | "
                     f"{tested:g} | **YES{' (gapped → fills at the open ' + format(tp.o[k], 'g') + ')' if gap else ''}** "
                     f"| — | — | — |")
            L += ["", f"→ exit at `{px:g}`, cause **{cause}**; `stop_at_exit = "
                  f"{stop:g}`, `best_px = {best:g}` (= `{r.side * (best - r.entry) / R:+.3f}R`).",
                  ""]
            return L
        prev_stop = stop
        if r.side > 0:
            best = max(best, tp.h[k])
            stop = max(stop, best - d)
        else:
            best = min(best, tp.l[k])
            stop = min(stop, best + d)
        n += 1
        if n <= MAX_RATCHET_ROWS:
            L.append(f"| {ny(tp.t[k])} | {tp.h[k]:g} | {tp.l[k]:g} | {tested:g} | "
                     f"no | {best:g} | {stop:g} | "
                     f"{'**yes, +' + format(abs(stop - prev_stop), 'g') + '**' if stop != prev_stop else 'no'} |")
        elif n == MAX_RATCHET_ROWS + 1:
            L.append(f"| … | | | | | | | *({b1 - k} further minutes; the full path "
                     f"is in the walker, not truncated there)* |")
    L += ["", f"→ no stop was hit by the {ny(tp.t[b1])} NY minute: **time-exit** at "
          f"that minute's close `{tp.c[b1]:g}`; `stop_at_exit = {stop:g}`, "
          f"`best_px = {best:g}` (= `{r.side * (best - r.entry) / R:+.3f}R`).", ""]
    return L


def _v(x):
    return "—" if pd.isna(x) else f"{x:.4f}"


if __name__ == "__main__":
    main()
