#!/usr/bin/env python3
"""PDH/PDL sweep engine — the **new level class**, drill-down pass (post-v4).

Spec: `knowledge/session-liquidity.md` §3.2 (PDH/PDL) and §5.1 **v4** (the iFVG
mechanic). This is a *sibling* of the v4 session-level engine, not a
replacement: it emits a **separate event stream** so the session-level tables
stay uncontaminated. Everything downstream of the level definition — the
block-scoped horizon, the **v4** iFVG confirmation state machine, the
magnitude/stop/R block — is the v4 engine's code, imported and called, not
re-implemented.

CONFIRMATION LAYER: `E.ifvg_confirm_v4` and `E._from_confirmation`, verbatim.
The v4 mechanic (sequential, latest-formed qualifying gap as the single active
candidate, **no invalidation**) is the pass's FIXED entry reference and is not
under test here. The first drill-down attempt used v2's retroactive best-pick
`ifvg_confirm`; every number it produced downstream of confirmation is stale and
was regenerated by this file.

The level class in one paragraph:
  * PDH/PDL = the high/low of the **entire prior UTC day, 00:00-24:00**, Late
    block included. The knowledge file is explicit that this deviates from the
    "max of the three session highs" shorthand, because the day's true extreme
    can print in 21:00-24:00; the share of days where it does is reported as a
    diagnostic (D4 in dd_tables).
  * Sweepable from the first bar of the following UTC day; lifetime is that day
    only (superseded at the next midnight). Retired on first take-out (V7).
  * A day-level take-out may coincide with a still-alive session level at the
    same price. That is legitimate and is not deduplicated — it is *flagged*
    (`coincident_session_level`, an alive session level within 0.05 x ATR of the
    day level at the take-out bar) so tables can split pure from coincident.

Writes results/pd_events_<SYM>.csv.

Usage: .venv/bin/python research/session-liquidity-v2/drilldown/pd_engine.py
"""
from __future__ import annotations

import argparse
import os

import numpy as np
import pandas as pd

import dd_common as D
from dd_common import C, E


# ---------------------------------------------------------------------------
def day_frames(d: pd.DataFrame) -> pd.DataFrame:
    """One row per UTC calendar day: the day's true extreme and its provenance.

    `late_set_high` / `late_set_low` record whether the 21:00-24:00 residual
    block is where the day's extreme actually printed — the diagnostic that
    justifies the knowledge file's "full day, Late included" choice over the
    session-max shorthand.

    `n_bars` gates the day: a day the data only partially covers cannot be
    trusted to carry the day's real extreme, so it defines no PDH/PDL (DD2).
    """
    day = d["ts"].dt.floor("D")
    late = d["block"].to_numpy() == "Late"
    g = pd.DataFrame({"day": day, "high": d.high, "low": d.low,
                      "late": late, "idx": np.arange(len(d))})
    agg = g.groupby("day", sort=True).agg(
        high=("high", "max"), low=("low", "min"),
        n_bars=("idx", "size"), first_idx=("idx", "min"), last_idx=("idx", "max"),
    ).reset_index()
    lt = g[g.late].groupby("day", sort=True).agg(
        late_high=("high", "max"), late_low=("low", "min")).reset_index()
    agg = agg.merge(lt, on="day", how="left")
    agg["late_set_high"] = agg.late_high >= agg.high
    agg["late_set_low"] = agg.late_low <= agg.low
    agg["valid"] = agg.n_bars >= D.PRIOR_DAY_MIN_BARS
    return agg


def session_pool_timeline(d: pd.DataFrame):
    """Replay the parent engine's session-level pool, bar by bar.

    Yields `(i, pool)` for every bar, with `pool` the alive session levels
    **before** bar `i`'s own take-outs retire anything — which is the state a
    coincidence test must see, since the same excursion that takes the day level
    is usually what takes the session level too.

    Admission (V1), expiry (V8) and retirement (V7) are copied from
    `engine.run_symbol` step-for-step; nothing about the session stream's own
    output is recomputed here.
    """
    hi = d["high"].to_numpy(); lo = d["low"].to_numpy()
    sess = C.session_frames(d)
    sess_rows = sess.to_dict("records")
    lookback_bars = int(C.LOOKBACK_HOURS * 60 / C.BAR_MIN)
    pool = {"high": [], "low": []}
    ptr = 0
    for i in range(len(d)):
        while ptr < len(sess_rows) and sess_rows[ptr]["known_from"] <= i:
            r = sess_rows[ptr]
            pool["high"].append(dict(px=r["high"], session=r["session"], end_idx=r["end_idx"]))
            pool["low"].append(dict(px=r["low"], session=r["session"], end_idx=r["end_idx"]))
            ptr += 1
        for side in ("high", "low"):
            pool[side] = [L for L in pool[side] if i - L["end_idx"] <= lookback_bars]
        yield i, pool
        for side in ("high", "low"):
            if side == "high":
                taken = [L for L in pool[side] if hi[i] > L["px"]]
            else:
                taken = [L for L in pool[side] if lo[i] < L["px"]]
            if taken:
                drop = {id(L) for L in taken}
                pool[side] = [L for L in pool[side] if id(L) not in drop]


# ---------------------------------------------------------------------------
def run_symbol(sym: str) -> pd.DataFrame:
    d = C.prep(C.load(sym))
    n = len(d)
    hi = d["high"].to_numpy(); lo = d["low"].to_numpy(); cl = d["close"].to_numpy()
    atrv = d["atr"].to_numpy(); ts = d["ts"].to_numpy(); blk = d["block"].to_numpy()
    ba = C.block_arrays(d)
    block_end = ba["block_end"]; bars_left = ba["bars_left"]; complete = ba["block_complete"]
    fv = E.fvg_arrays(d)

    days = day_frames(d)
    days["prev_high"] = days.high.shift(1)
    days["prev_low"] = days.low.shift(1)
    days["prev_valid"] = days.valid.shift(1).fillna(False).infer_objects(copy=False).astype(bool)
    days["prev_last_idx"] = days.last_idx.shift(1)
    days["prev_range"] = days.prev_high - days.prev_low

    # bar -> the (PDH, PDL) pair in force on that bar, and the prior day's meta
    pdh = np.full(n, np.nan); pdl = np.full(n, np.nan)
    prng = np.full(n, np.nan); pend = np.full(n, np.nan)
    for _, r in days.iterrows():
        if not r.prev_valid or not np.isfinite(r.prev_high):
            continue
        a, b = int(r.first_idx), int(r.last_idx)
        pdh[a:b + 1] = r.prev_high
        pdl[a:b + 1] = r.prev_low
        prng[a:b + 1] = r.prev_range
        pend[a:b + 1] = r.prev_last_idx

    # ---- pass 1: first take-out of each side, per day (V7 retires the level)
    day_id = d["ts"].dt.floor("D").factorize()[0]
    hit_bars: dict[tuple[int, str], int] = {}
    for i in range(n):
        for side, cond in (("high", np.isfinite(pdh[i]) and hi[i] > pdh[i]),
                           ("low", np.isfinite(pdl[i]) and lo[i] < pdl[i])):
            k = (day_id[i], side)
            if cond and k not in hit_bars:
                hit_bars[k] = i
    event_bars = {}
    for (di, side), i in hit_bars.items():
        event_bars.setdefault(i, []).append(side)

    # ---- pass 2: the coincidence flag needs the session pool's live state ---
    coincident: dict[tuple[int, str], tuple[bool, float]] = {}
    for i, pool in session_pool_timeline(d):
        if i not in event_bars:
            continue
        a = atrv[i]
        tol = D.COINCIDENCE_ATR * a if np.isfinite(a) else np.nan
        for side in event_bars[i]:
            lvl = pdh[i] if side == "high" else pdl[i]
            near = [L for L in pool[side] if abs(L["px"] - lvl) <= tol] if np.isfinite(tol) else []
            coincident[(i, side)] = (len(near) > 0,
                                     min((abs(L["px"] - lvl) / a for L in near), default=np.nan))

    # ---- pass 3: measure, reusing the parent engine's block-scoped machinery -
    events = []
    for i in sorted(event_bars):
        for side in event_bars[i]:
            level = pdh[i] if side == "high" else pdl[i]
            if not complete[i]:
                continue
            a = atrv[i]
            if not np.isfinite(a) or a <= 0:
                continue
            be = int(block_end[i]); left = int(bars_left[i])
            ref = hi[i] if side == "high" else lo[i]
            co, co_d = coincident.get((i, side), (False, np.nan))
            ev = dict(
                symbol=sym, ts=pd.Timestamp(ts[i]), bar=i,
                month=d["month"].iat[i],
                direction="high_sweep" if side == "high" else "low_sweep",
                level_session=D.PD_SESSION,       # DD1 — never Asia/London/NY
                sweep_block=blk[i],
                level_px=level, n_levels_taken=1,
                level_age_h=(i - pend[i]) * C.BAR_MIN / 60.0,
                sweep_ref=ref, atr=a,
                block_end_bar=be, bars_remaining=left, window_min=left * C.BAR_MIN,
                excursion_pct=abs(ref - level) / level * 100,
                excursion_atr=abs(ref - level) / a,
                struct_range=prng[i],            # prior day's range (denominator #2)
                coincident_session_level=bool(co),
                coincident_dist_atr=co_d,
            )
            if left > 0:
                fw_lo = lo[i + 1:be + 1].min(); fw_hi = hi[i + 1:be + 1].max()
                end_c = cl[be]
                if side == "high":
                    rev_raw = ref - fw_lo; adv_raw = fw_hi - ref; end_abs = ref - end_c
                else:
                    rev_raw = fw_hi - ref; adv_raw = ref - fw_lo; end_abs = end_c - ref
                rev_abs = max(rev_raw, 0.0); adv_abs = max(adv_raw, 0.0)
                ev.update(rev_pct=rev_abs / ref * 100, rev_atr=rev_abs / a,
                          adv_pct=adv_abs / ref * 100, adv_atr=adv_abs / a,
                          end_pct=end_abs / ref * 100, end_atr=end_abs / a,
                          no_continuation=adv_raw <= 0, no_reversal=rev_raw <= 0)
            else:
                ev.update(rev_pct=np.nan, rev_atr=np.nan, adv_pct=np.nan, adv_atr=np.nan,
                          end_pct=np.nan, end_atr=np.nan,
                          no_continuation=np.nan, no_reversal=np.nan)

            # iFVG confirmation — the **v4** state machine (§5.1 V9), verbatim
            r4 = E.ifvg_confirm_v4(fv, cl, i, be, level, side, strict=False)
            if_idx = r4["confirm_idx"]; if_form = r4["form_idx"]
            rs = E.ifvg_confirm_v4(fv, cl, i, be, level, side, strict=True)
            st_idx = rs["confirm_idx"]
            ev.update(ifvg_confirmed=if_idx >= 0,
                      ifvg_delay_bars=(if_idx - i) if if_idx >= 0 else np.nan,
                      ifvg_form_bar=if_form if if_form >= 0 else np.nan,
                      ifvg_form_delay_bars=(if_form - i) if if_form >= 0 else np.nan,
                      n_candidates=r4["n_candidates"],
                      n_replacements=r4["n_replacements"],
                      unconf_cause=r4["cause"],
                      ifvg_strict_confirmed=st_idx >= 0,
                      ifvg_strict_delay_bars=(st_idx - i) if st_idx >= 0 else np.nan)
            if if_idx < 0:
                probe_end = min(be + C.TRUNCATION_PROBE_BARS, n - 1)
                rp = E.ifvg_confirm_v4(fv, cl, i, probe_end, level, side, strict=False)
                ev["ifvg_would_confirm_extended"] = rp["confirm_idx"] >= 0
                ev["ifvg_extended_delay_bars"] = (rp["confirm_idx"] - i) \
                    if rp["confirm_idx"] >= 0 else np.nan
            else:
                ev["ifvg_would_confirm_extended"] = False
                ev["ifvg_extended_delay_bars"] = np.nan

            # from-confirmation geometry: the v4 engine's own `_from_confirmation`,
            # called rather than re-typed, so the day-level stream and the
            # session-level stream can never drift in how MFE/MAE/stop/R are
            # measured.
            if if_idx >= 0 and if_idx < be:
                g = E._from_confirmation(hi, lo, cl, a, i, if_idx, be, side)
                ev.update({(k_ if k_ in ("conf_close", "conf_bars_remaining")
                            else "ifvg_" + k_): v for k_, v in g.items()})
            else:
                for c_ in E.CONF_COLS:
                    ev[c_ if c_ in ("conf_close", "conf_bars_remaining")
                       else "ifvg_" + c_] = np.nan
            events.append(ev)
    return pd.DataFrame(events)


def day_diag(sym: str) -> pd.DataFrame:
    d = C.prep(C.load(sym))
    df = day_frames(d)
    df["symbol"] = sym
    return df


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", default=",".join(D.SYMBOLS))
    a = ap.parse_args()
    diag = []
    for sym in a.symbols.split(","):
        ev = run_symbol(sym)
        ev.to_csv(os.path.join(D.RESULTS, f"pd_events_{sym}.csv"), index=False)
        diag.append(day_diag(sym))
        prim = ev[ev.bars_remaining >= D.MINB]
        print(f"{sym}: {len(ev):>5} PDH/PDL take-outs ({len(prim):>5} primary) | "
              f"iFVG {ev.ifvg_confirmed.mean():.1%} (primary {prim.ifvg_confirmed.mean():.1%}) | "
              f"coincident {ev.coincident_session_level.mean():.1%}", flush=True)
    pd.concat(diag, ignore_index=True).to_csv(
        os.path.join(D.RESULTS, "pd_day_frames.csv"), index=False)


if __name__ == "__main__":
    main()
