/**
 * IB-016 — the exponential moving average §8.2's two trend keys need.
 *
 * **This is `emaOf` from `libs/indicators/src/series.ts`, lifted verbatim, not a new one.** The
 * recurrence and — critically — the SEEDING are identical: seeded at index `length − 1` with the
 * SMA of the first `length` closes, then `ema = α·x + (1 − α)·ema_prev` with `α = 2/(length + 1)`.
 * That is TA-Lib's default and TradingView's `ta.ema`.
 *
 * The seeding is the part worth copying exactly, and it is why `seed: 'sma'` is a registry
 * parameter rather than an implementation detail. An EMA seeded with the first close and one
 * seeded with the SMA of the first `length` closes disagree for roughly `length` bars and then
 * converge — so two readers of "EMA200" would get different numbers for two hundred days and
 * identical numbers afterwards. A disagreement that heals itself is the hardest kind to notice.
 *
 * **Why a copy rather than an import.** `apps/insight-bot` does not depend on
 * `@trade-automation/indicators`; `apps/signal-server` and `apps/chart-client` do. The same
 * question was ruled on for `wilderAtr` in this directory on 2026-10-12 — lift with a signpost,
 * do not add the dependency, BUG-024 decides whether the three consolidate. This follows that
 * ruling. Unlike the ATR case, where `libs/indicators` holds a DIFFERENT statistic (arithmetic
 * mean, not Wilder's) and reuse would have been wrong, here the shared one is exactly right and
 * the only argument for copying is the dependency boundary. That makes this the stronger
 * candidate of the two for BUG-024 to resolve by importing.
 *
 * The cross-check spec pins this by NUMBERS: every expectation in `test/features/ema.spec.ts`
 * was generated by running `libs/indicators`' own `emaOf`, so the two cannot drift silently.
 *
 * **BUG-024's decision criterion, recorded by the Tech Lead on 2026-10-12 so it is not
 * re-argued:** pinning by generated numbers suffices while the primitive is small enough to pin
 * by value. The trigger to switch to an import is a primitive too parameterised to pin, or a
 * THIRD copy — two is a coincidence, three is a structural answer.
 */

/**
 * EMA of `closes` at the last bar, or null when there are fewer than `length` of them.
 *
 * Null rather than a shorter average: an EMA50 over 30 bars is a number, but it is not the
 * number the key's definition claims, and nothing downstream could tell the difference.
 */
export function emaLast(closes: readonly number[], length: number): number | null {
  if (!Number.isInteger(length) || length <= 0) {
    throw new Error(`emaLast: length must be a positive integer, got ${length}`);
  }
  if (closes.length < length) return null;

  // Seed: the SMA of the first `length` closes, at index length - 1.
  let seed = 0;
  for (let i = 0; i < length; i++) seed += closes[i] as number;
  let value = seed / length;

  const alpha = 2 / (length + 1);
  for (let i = length; i < closes.length; i++) {
    value = alpha * (closes[i] as number) + (1 - alpha) * value;
  }
  return value;
}
