import { emaLast } from '../../src/features/math/ema';
import { emaFeatures } from '../../src/features/calculators/ema';
import { featureParamNumber } from '@trade-automation/contracts';

/**
 * IB-016 — the EMA, pinned so it cannot drift from `libs/indicators`.
 *
 * `apps/insight-bot` does not depend on `@trade-automation/indicators`, so this is a verbatim
 * lift of its `emaOf` (the ruling of 2026-10-12 for `wilderAtr`; BUG-024 decides whether the
 * copies consolidate). A copy that cannot be imported has to be pinned by its NUMBERS instead,
 * which is what the first block below does: every expectation was generated by running
 * `libs/indicators`' own `emaOf` and pasted here. If either implementation is changed, these
 * fail.
 */
const SERIES = [103.5, 99.2, 107.8, 95.1, 112.4, 88.7, 120.3, 101.9, 94.6, 115.2, 108.8, 97.3];

describe('emaLast agrees with libs/indicators emaOf', () => {
  // Generated from libs/indicators/dist/series.js on 2026-10-12, not computed by hand here:
  // hand-computing would be a second implementation, which is the thing being guarded against.
  const EXPECTED: ReadonlyArray<readonly [number, number]> = [
    [1, 97.3],
    [3, 102.746484375],
    [5, 103.67027892089624],
    [12, 103.73333333333333],
  ];

  it.each(EXPECTED)('length %i', (length, expected) => {
    expect(emaLast(SERIES, length)).toBeCloseTo(expected, 10);
  });

  it('seeds with the SMA, which is the part that silently diverges', () => {
    // With exactly `length` bars the EMA IS the SMA of them — no recurrence steps have run yet.
    // An implementation seeded with the FIRST CLOSE instead would give 97.3 here, and would
    // agree again after ~length bars, which is why `seed` is a registry parameter.
    const sma = SERIES.reduce((a, b) => a + b, 0) / SERIES.length;
    expect(emaLast(SERIES, SERIES.length)).toBeCloseTo(sma, 10);
    expect(emaLast(SERIES, SERIES.length)).not.toBeCloseTo(SERIES[SERIES.length - 1] as number, 5);
  });
});

describe('emaLast refuses rather than shortening', () => {
  it('is null below `length` bars — an EMA50 over 30 bars is not an EMA50', () => {
    expect(emaLast(SERIES.slice(0, 11), 12)).toBeNull();
    expect(emaLast([], 1)).toBeNull();
  });

  it('computes at exactly `length` bars, the boundary', () => {
    expect(emaLast(SERIES.slice(0, 12), 12)).not.toBeNull();
  });

  it('throws on a nonsensical length rather than returning something', () => {
    expect(() => emaLast(SERIES, 0)).toThrow(/positive integer/);
    expect(() => emaLast(SERIES, 2.5)).toThrow(/positive integer/);
  });
});

describe('emaFeatures', () => {
  const closes = (n: number) => Array.from({ length: n }, (_, i) => 100 + Math.sin(i) * 5);

  /**
   * IB-052 — the key's window is `length + warmupBars`, and this spec reads both from the
   * registry rather than naming 50 and 200. The EMA is recursive, so a value computed from
   * `length` closes is not the same number as one computed from `length + warmup` closes; the
   * window is therefore part of the key's definition and lives where the definition lives.
   */
  const window = (key: 'ema.4h.50' | 'ema.1d.200') =>
    featureParamNumber(key, 'length') + featureParamNumber(key, 'warmupBars');

  it('refuses both keys on today’s tape, which is the stated prerequisite not a defect', () => {
    // candles_agg holds about ten days, so ema.1d.200 cannot be computed until the archive
    // backfill lands. `insufficient_history` says that; a number would claim a trend nobody has
    // evidence for.
    const out = emaFeatures({ closes4h: closes(10), closes1d: closes(10) });
    expect(out['ema.4h.50']).toEqual({ ok: false, why: 'insufficient_history' });
    expect(out['ema.1d.200']).toEqual({ ok: false, why: 'insufficient_history' });
  });

  it('computes each key once its own window is filled, independently', () => {
    const out = emaFeatures({ closes4h: closes(window('ema.4h.50')), closes1d: closes(10) });
    expect(out['ema.4h.50']?.ok).toBe(true);
    expect(out['ema.1d.200']?.ok).toBe(false); // one key's history does not vouch for another's
  });

  it('uses the WINDOW the registry declares, not a literal', () => {
    // The guard against the key's name, its parameters and the number of closes used drifting
    // apart. Since IB-052 the boundary is length + warmupBars, not length: an EMA50 over exactly
    // 50 closes is the SMA of them, which is a different quantity from the one this key names.
    expect(featureParamNumber('ema.4h.50', 'length')).toBe(50);
    expect(emaFeatures({ closes4h: closes(window('ema.4h.50') - 1), closes1d: [] })['ema.4h.50']?.ok).toBe(false);
    expect(emaFeatures({ closes4h: closes(window('ema.4h.50')), closes1d: [] })['ema.4h.50']?.ok).toBe(true);
  });
});
